//! Graph node pins (UEdGraphPin), saved by UEdGraphNode::Serialize after the
//! node's tagged properties. Niagara keeps module input values here: the
//! override pins of a NiagaraNodeParameterMapSet / NiagaraNodeFunctionCall
//! carry `DefaultValue` strings, and `LinkedTo` wires the graph.

use crate::package::{PackageIndex, Versions};
use crate::property::{read_pin_type, Ctx, Property, Text, Value};
use crate::reader::{Guid, Reader, Result};
use crate::summary::custom;

/// EEdGraphPinDirection.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Direction {
    Input,
    Output,
}

/// A reference to a pin: the node export that owns it and the pin's id.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PinRef {
    pub node: PackageIndex,
    pub pin: Guid,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Pin {
    pub id: Guid,
    pub name: String,
    pub friendly_name: Option<Text>,
    pub source_index: i32,
    pub tooltip: String,
    pub direction: Direction,
    /// FEdGraphPinType fields (PinCategory, PinSubCategory,
    /// PinSubCategoryObject, ContainerType, ...).
    pub pin_type: Vec<Property>,
    pub default_value: String,
    pub autogenerated_default_value: String,
    pub default_object: PackageIndex,
    pub default_text: Text,
    pub linked_to: Vec<PinRef>,
    pub sub_pins: Vec<PinRef>,
    pub parent_pin: Option<PinRef>,
    pub reference_pass_through: Option<PinRef>,
    pub persistent_guid: Guid,
    /// bHidden, bNotConnectable, bDefaultValueIsReadOnly, ... bits.
    pub bits: u32,
}

impl Pin {
    /// A field of the pin type, e.g. "PinCategory".
    pub fn type_field(&self, name: &str) -> Option<&Value> {
        crate::property::find(&self.pin_type, name)
    }
    /// The pin type's PinSubCategoryObject (for Niagara pins: the type
    /// struct, e.g. NiagaraFloat).
    pub fn type_object(&self) -> PackageIndex {
        match self.type_field("PinSubCategoryObject") {
            Some(Value::Object(i)) => *i,
            _ => PackageIndex(0),
        }
    }
}

/// Whether exports of this class serialize pins (UEdGraphNode subclasses).
pub fn is_graph_node_class(class: &str) -> bool {
    class.starts_with("NiagaraNode") || class.starts_with("EdGraphNode") || class.starts_with("K2Node")
}

/// Whether the package saves pins in the UE 4.19+ layout this reader knows.
pub fn pins_supported(v: &Versions) -> bool {
    !v.filter_editor_only && v.blueprints_object.unwrap_or(0) >= custom::BLUEPRINTS_EDGRAPH_PIN_OPTIMIZED
}

/// The owning node's pin array.
pub fn read_pins(r: &mut Reader, ctx: &mut Ctx) -> Result<Vec<Pin>> {
    let n = r.count(4)?;
    let mut pins = Vec::with_capacity(n);
    for _ in 0..n {
        if r.bool32()? {
            continue; // null pin
        }
        // The reference, then the pin itself (which starts with the same
        // owning node and pin id again).
        let _owner = PackageIndex(r.i32()?);
        let _id = r.guid()?;
        let _owner = PackageIndex(r.i32()?);
        let id = r.guid()?;
        pins.push(read_pin(r, ctx, id)?);
    }
    Ok(pins)
}

fn read_pin_ref(r: &mut Reader) -> Result<Option<PinRef>> {
    if r.bool32()? {
        return Ok(None);
    }
    Ok(Some(PinRef {
        node: PackageIndex(r.i32()?),
        pin: r.guid()?,
    }))
}

fn read_pin_refs(r: &mut Reader) -> Result<Vec<PinRef>> {
    let n = r.count(4)?;
    let mut v = Vec::with_capacity(n);
    for _ in 0..n {
        if let Some(p) = read_pin_ref(r)? {
            v.push(p);
        }
    }
    Ok(v)
}

fn read_pin(r: &mut Reader, ctx: &mut Ctx, id: Guid) -> Result<Pin> {
    let name = ctx.fname_pub(r)?;
    ctx.push_path(format!("pin {name}"));
    let res = (|| -> Result<Pin> {
        let friendly_name = Some(ctx.text(r, false)?);
        let source_index = if ctx.v.ue5_main_stream.unwrap_or(0) >= custom::UE5_MAIN_EDGRAPH_PIN_SOURCE_INDEX {
            r.i32()?
        } else {
            -1
        };
        let tooltip = r.fstring()?;
        let at = r.pos();
        let direction = match r.u8()? {
            0 => Direction::Input,
            1 => Direction::Output,
            d => return Err(crate::reader::Error::new(at, format!("bad pin direction {d}"))),
        };
        let pin_type = read_pin_type(r, ctx)?;
        let default_value = r.fstring()?;
        let autogenerated_default_value = r.fstring()?;
        let default_object = PackageIndex(r.i32()?);
        let default_text = ctx.text(r, false)?;
        let linked_to = read_pin_refs(r)?;
        let sub_pins = read_pin_refs(r)?;
        let parent_pin = read_pin_ref(r)?;
        let reference_pass_through = read_pin_ref(r)?;
        let persistent_guid = r.guid()?;
        let bits = r.u32()?;
        Ok(Pin {
            id,
            name: name.clone(),
            friendly_name,
            source_index,
            tooltip,
            direction,
            pin_type,
            default_value,
            autogenerated_default_value,
            default_object,
            default_text,
            linked_to,
            sub_pins,
            parent_pin,
            reference_pass_through,
            persistent_guid,
            bits,
        })
    })();
    ctx.pop_path();
    res
}
